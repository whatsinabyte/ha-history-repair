    def _apply_one_correction(
        self,
        cur: Any,
        *,
        entity_id: str,
        sensor_type: SensorType,
        stats_metadata: StatisticsMetadata | None,
        state_id: int,
        expected_original: str | None,
        new_value: str,
        quality: Quality,
        note: str | None,
        created_by: str,
    ) -> int:
        """Correct one row on an already-open transaction. Returns the audit id.

        This is the single unit of work shared by apply_correction (one row,
        its own transaction) and apply_bulk_correction (many rows, one shared
        transaction, applied in chronological order). Nothing here opens or
        closes a transaction — the caller owns that.
        """
        # Lock the target row and confirm it is the one the user saw.
        # FOR UPDATE OF s, not a bare FOR UPDATE: PostgreSQL would otherwise
        # take a row lock on the joined states_meta row as well, which nothing
        # here is modifying and which every other correction for the same
        # entity would then contend on.
        cur.execute(
            """
            SELECT s.state_id, s.state, s.last_updated_ts, sm.entity_id
              FROM states s
              JOIN states_meta sm ON sm.metadata_id = s.metadata_id
             WHERE s.state_id = %s
             FOR UPDATE OF s
            """,
            (state_id,),
        )
        row = cur.fetchone()
        if not row:
            raise NotFound(f"No states row with id {state_id}")
        if row["entity_id"] != entity_id:
            raise NotFound(f"States row {state_id} belongs to {row['entity_id']}, not {entity_id}")
        if expected_original is not None and row["state"] != expected_original:
            raise ConcurrentModification(
                f"This value changed since you loaded it: it now reads "
                f"'{row['state']}', not '{expected_original}'. Reload the graph "
                "and try again."
            )

        ts = float(row["last_updated_ts"])
        state_dt = datetime.fromtimestamp(ts, tz=timezone.utc).replace(tzinfo=None)

        # Audit first: if the UPDATE below fails, this rolls back with it
        # and the database is left untouched (design document, 9.9).
        # RETURNING replaces lastrowid, which psycopg does not provide.
        cur.execute(
            """
            INSERT INTO state_corrections
              (entity_id, sensor_type, state_id, state_ts, state_dt,
               orig_state_value, corrected_value, quality, note,
               created_by, stats_corrected)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, FALSE)
            RETURNING id
            """,
            (
                entity_id,
                sensor_type.value,
                state_id,
                ts,
                state_dt,
                row["state"],
                new_value,
                quality.value,
                note,
                created_by,
            ),
        )
        correction_id = int(cur.fetchone()["id"])

        cur.execute(
            "UPDATE states SET state = %s WHERE state_id = %s",
            (new_value, state_id),
        )
        if cur.rowcount != 1:
            raise NotFound(f"States row {state_id} disappeared mid-transaction")

        if stats_metadata is not None:
            # Only now, with the corrected value committed to this
            # transaction, can the buckets be rebuilt from it.
            cascade_delta: float | None = None
            cascade_rows: int | None = None
            if sensor_type is SensorType.COUNTER:
                (
                    originals_short,
                    originals_hourly,
                    cascade_rows,
                    cascade_delta,
                ) = self._recompute_counter_statistics(cur, entity_id, stats_metadata.id, ts)
            else:
                originals_short, originals_hourly, _ = self._recompute_measurement_statistics(
                    cur, entity_id, stats_metadata.id, ts
                )
            # The originals are recorded on the same audit row, so a
            # restore can put the statistics back exactly as they were
            # rather than recomputing and hoping.
            cur.execute(
                """
                UPDATE state_corrections SET
                  orig_sst_mean = %s, orig_sst_min = %s, orig_sst_max = %s,
                  orig_sst_state = %s, orig_sst_sum = %s,
                  orig_stat_mean = %s, orig_stat_min = %s, orig_stat_max = %s,
                  orig_stat_state = %s, orig_stat_sum = %s,
                  sum_delta_applied = %s, cascade_rows_updated = %s,
                  stats_corrected = TRUE
                WHERE id = %s
                """,
                (
                    originals_short.get("mean"),
                    originals_short.get("min"),
                    originals_short.get("max"),
                    originals_short.get("state"),
                    originals_short.get("sum"),
                    originals_hourly.get("mean"),
                    originals_hourly.get("min"),
                    originals_hourly.get("max"),
                    originals_hourly.get("state"),
                    originals_hourly.get("sum"),
                    cascade_delta,
                    cascade_rows,
                    correction_id,
                ),
            )

        return correction_id

    def apply_correction(
        self,
        *,
        entity_id: str,
        state_id: int,
        expected_original: str | None,
        new_value: str,
        quality: Quality,
        note: str | None,
        created_by: str,
        recompute_statistics: bool = False,
    ) -> Correction:
        # Resolved before the transaction opens so no second connection is
        # needed while a row lock is held.
        sensor_type = self.get_entity(entity_id).sensor_type
        stats_metadata = self.get_statistics_metadata(entity_id) if recompute_statistics else None

        with self._transaction() as cur:
            correction_id = self._apply_one_correction(
                cur,
                entity_id=entity_id,
                sensor_type=sensor_type,
                stats_metadata=stats_metadata,
                state_id=state_id,
                expected_original=expected_original,
                new_value=new_value,
                quality=quality,
                note=note,
                created_by=created_by,
            )

        return self.get_correction(correction_id)

    def _restore_statistics(self, cur: Any, correction: dict[str, Any]) -> None:
        """Write the statistics values recorded at correction time back.

        Both rows are addressed by (metadata_id, start_ts), the natural key of
        a statistics bucket. A row that has since been purged is simply skipped
        — there is nothing left to put back, and that is not a failure.
        """
        stats_metadata = self.get_statistics_metadata(correction["entity_id"])
        if stats_metadata is None:
            return

        state_ts = float(correction["state_ts"])

        cur.execute(
            "UPDATE statistics_short_term SET mean = %s, min = %s, max = %s "
            "WHERE metadata_id = %s AND start_ts = %s",
            (
                correction["orig_sst_mean"],
                correction["orig_sst_min"],
                correction["orig_sst_max"],
                stats_metadata.id,
                bucket_start(state_ts, SHORT_TERM_SECONDS),
            ),
        )
        cur.execute(
            "UPDATE statistics SET mean = %s, min = %s, max = %s "
            "WHERE metadata_id = %s AND start_ts = %s",
            (
                correction["orig_stat_mean"],
                correction["orig_stat_min"],
                correction["orig_stat_max"],
                stats_metadata.id,
                bucket_start(state_ts, HOURLY_SECONDS),
            ),
        )

    def restore_correction(self, correction_id: int, restored_by: str) -> Correction:
        with self._transaction() as cur:
            cur.execute(
                "SELECT id, entity_id, state_id, state_ts, orig_state_value, "
                "corrected_value, restored_at, stats_corrected, "
                "orig_sst_mean, orig_sst_min, orig_sst_max, "
                "orig_stat_mean, orig_stat_min, orig_stat_max "
                "FROM state_corrections WHERE id = %s FOR UPDATE",
                (correction_id,),
            )
            correction = cur.fetchone()
            if not correction:
                raise NotFound(f"No correction with id {correction_id}")
            if correction["restored_at"] is not None:
                raise ConcurrentModification("This correction has already been restored.")
            if correction["state_id"] is None:
                raise NotFound(
                    "This correction has no states row recorded and cannot be "
                    "restored automatically."
                )

            cur.execute(
                "SELECT state FROM states WHERE state_id = %s FOR UPDATE",
                (correction["state_id"],),
            )
            current = cur.fetchone()
            if not current:
                raise NotFound(
                    "The corrected states row no longer exists — it was most likely "
                    "purged by the recorder."
                )
            if current["state"] != correction["corrected_value"]:
                # Someone else changed this row, or a backup was restored over
                # it. Refuse rather than overwrite a value we did not write.
                raise ConcurrentModification(
                    f"This row now holds '{current['state']}', not the corrected value "
                    f"'{correction['corrected_value']}'. It was changed outside this "
                    "add-on, so it will not be overwritten."
                )

            cur.execute(
                "UPDATE states SET state = %s WHERE state_id = %s",
                (correction["orig_state_value"], correction["state_id"]),
            )

            if correction["stats_corrected"]:
                metadata = self.get_statistics_metadata(correction["entity_id"])
                if metadata is not None and metadata.has_sum:
                    # A counter cannot be restored from stored values: the
                    # correction rewrote every later running total, and there
                    # could be thousands of them. The chain is rebuilt instead,
                    # now that the state is back to its original — the same
                    # computation that produced those totals, run over the
                    # original data, reproduces them.
                    self._recompute_counter_statistics(
                        cur,
                        correction["entity_id"],
                        metadata.id,
                        float(correction["state_ts"]),
                    )
                else:
                    # A measurement correction touches two rows, so their
                    # previous values were recorded and are put back verbatim.
                    # Recomputing would derive whatever the data now implies,
                    # which is not necessarily what Home Assistant had written.
                    self._restore_statistics(cur, correction)

            cur.execute(
                "UPDATE state_corrections SET restored_at = (NOW() AT TIME ZONE 'utc'), "
                "restored_by = %s WHERE id = %s",
                (restored_by, correction_id),
            )

        return self.get_correction(correction_id)

    def find_orphaned_corrections(self) -> list[Correction]:
        # LEFT JOIN so a states row purged by the recorder (not merely
        # reverted by a backup) also counts as orphaned rather than silently
        # disappearing from the check.
        #
        # No COLLATE clause is needed on the s.state != c.corrected_value
        # comparison, unlike the MariaDB adapter: both columns are VARCHAR in
        # the same database collation, so PostgreSQL compares them directly
        # rather than raising the collation-mismatch error MySQL does.
        with self._cursor() as cur:
            cur.execute(
                # nosec B608 - _CORRECTION_COLUMNS_QUALIFIED is a module constant
                f"SELECT {_CORRECTION_COLUMNS_QUALIFIED} "  # nosec B608
                "FROM state_corrections c "
                "LEFT JOIN states s ON s.state_id = c.state_id "
                "WHERE c.restored_at IS NULL AND c.dismissed_at IS NULL "
                "AND c.state_id IS NOT NULL "
                "AND (s.state_id IS NULL OR s.state != c.corrected_value) "
                "ORDER BY c.created_at DESC, c.id DESC"
            )
            return [self._row_to_correction(r) for r in cur.fetchall()]

    def dismiss_correction(self, correction_id: int, dismissed_by: str) -> Correction:
        with self._transaction() as cur:
            cur.execute(
                "SELECT id, restored_at, dismissed_at FROM state_corrections "
                "WHERE id = %s FOR UPDATE",
                (correction_id,),
            )
            correction = cur.fetchone()
            if not correction:
                raise NotFound(f"No correction with id {correction_id}")
            if correction["restored_at"] is not None:
                raise ConcurrentModification(
                    "This correction has already been restored and cannot be dismissed."
                )
            if correction["dismissed_at"] is not None:
                raise ConcurrentModification("This correction has already been dismissed.")

            cur.execute(
                "UPDATE state_corrections SET dismissed_at = (NOW() AT TIME ZONE 'utc'), "
                "dismissed_by = %s WHERE id = %s",
                (dismissed_by, correction_id),
            )

        return self.get_correction(correction_id)

    # -- bulk correction -------------------------------------------------

    def _bulk_target_rows(
        self, cur: Any, entity_id: str, start_ts: float, end_ts: float
    ) -> list[dict[str, Any]]:
        """Raw state rows in range, oldest first, each flagged if already corrected.

        Ordering matters beyond presentation: apply_bulk_correction applies
        rows chronologically so that, for a counter, each row's cascade
        inherits the correct running total from the row before it — which by
        the time it runs has already been fixed by this same loop.
        """
        cur.execute(
            """
            SELECT s.state_id, s.state, s.last_updated_ts AS ts
              FROM states s
              JOIN states_meta sm ON sm.metadata_id = s.metadata_id
             WHERE sm.entity_id = %s
               AND s.last_updated_ts >= %s
               AND s.last_updated_ts < %s
             ORDER BY s.last_updated_ts
            """,
            (entity_id, start_ts, end_ts),
        )
        rows: list[dict[str, Any]] = list(cur.fetchall())

        # The savepoint matters more here than anywhere else: this runs inside
        # the bulk correction's own write transaction, so without it a missing
        # audit table would abort the entire batch rather than just this one
        # optional lookup.
        try:
            with self._savepoint(cur):
                cur.execute(
                    "SELECT state_id FROM state_corrections "
                    "WHERE entity_id = %s AND restored_at IS NULL "
                    "AND state_ts >= %s AND state_ts < %s AND state_id IS NOT NULL",
                    (entity_id, start_ts, end_ts),
                )
                already_corrected = {r["state_id"] for r in cur.fetchall()}
        except psycopg.Error as err:
            if not self._is_missing_audit_table(err):
                raise
            already_corrected = set()

        for row in rows:
            row["already_corrected"] = row["state_id"] in already_corrected
        return rows

    def _interpolation_anchors(
        self, cur: Any, entity_id: str, start_ts: float, end_ts: float
    ) -> tuple[Reading | None, Reading | None]:
        """The nearest numeric readings just outside the range, if any.

        Both are needed to interpolate: the reading in effect right before the
        range, and the first real reading once it resumes. Either can be
        missing — the range might start at the very beginning of an entity's
        history, or the entity might never report again.
        """
        cur.execute(
            """
            SELECT s.state, s.last_updated_ts
              FROM states s
              JOIN states_meta sm ON sm.metadata_id = s.metadata_id
             WHERE sm.entity_id = %s
               AND s.last_updated_ts < %s
               AND s.state NOT IN ('unknown', 'unavailable')
             ORDER BY s.last_updated_ts DESC
             LIMIT 1
            """,
            (entity_id, start_ts),
        )
        before_row = cur.fetchone()

        cur.execute(
            """
            SELECT s.state, s.last_updated_ts
              FROM states s
              JOIN states_meta sm ON sm.metadata_id = s.metadata_id
             WHERE sm.entity_id = %s
               AND s.last_updated_ts >= %s
               AND s.state NOT IN ('unknown', 'unavailable')
             ORDER BY s.last_updated_ts
             LIMIT 1
            """,
            (entity_id, end_ts),
        )
        after_row = cur.fetchone()

        before = None
        if before_row is not None:
            value = to_float(before_row["state"])
            if value is not None:
                before = Reading(value=value, ts=float(before_row["last_updated_ts"]))

        after = None
        if after_row is not None:
            value = to_float(after_row["state"])
            if value is not None:
                after = Reading(value=value, ts=float(after_row["last_updated_ts"]))

        return before, after

    def bulk_correction_preview(
        self, entity_id: str, start_ts: float, end_ts: float
    ) -> BulkPreview:
        with self._cursor() as cur:
            rows = self._bulk_target_rows(cur, entity_id, start_ts, end_ts)
            before, after = self._interpolation_anchors(cur, entity_id, start_ts, end_ts)

        already_corrected = sum(1 for r in rows if r["already_corrected"])
        return BulkPreview(
            total=len(rows),
            correctable=len(rows) - already_corrected,
            already_corrected=already_corrected,
            can_interpolate=before is not None and after is not None,
        )

    def apply_bulk_correction(
        self,
        *,
        entity_id: str,
        start_ts: float,
        end_ts: float,
        strategy: str,
        value: str | None,
        quality: Quality,
        note: str | None,
        created_by: str,
    ) -> BulkCorrectionResult:
        sensor_type = self.get_entity(entity_id).sensor_type
        stats_metadata = self.get_statistics_metadata(entity_id)

        with self._transaction() as cur:
            rows = self._bulk_target_rows(cur, entity_id, start_ts, end_ts)
            targets = [r for r in rows if not r["already_corrected"]]

            if len(targets) > MAX_BULK_ROWS:
                raise InvalidRange(
                    f"This range holds {len(targets)} correctable rows, more than the "
                    f"{MAX_BULK_ROWS}-row limit for a single bulk correction. Choose a "
                    "narrower range."
                )

            # Resolved once, up front, into a single value_for(ts) function —
            # rather than branching on `strategy` inside the loop with an
            # assert to narrow the type. Asserts are stripped under python -O,
            # which would leave a wrong branch silently reachable in exactly
            # the build that ships.
            if strategy == "interpolate":
                before, after = self._interpolation_anchors(cur, entity_id, start_ts, end_ts)
                if before is None or after is None:
                    raise InvalidRange(
                        "Cannot interpolate: this range needs a numeric reading on both "
                        "sides of it, and at least one side has none."
                    )
                anchor_before, anchor_after = before, after

                def value_for(ts: float) -> str:
                    span = anchor_after.ts - anchor_before.ts
                    fraction = (ts - anchor_before.ts) / span if span else 0.0
                    interpolated = (
                        anchor_before.value + (anchor_after.value - anchor_before.value) * fraction
                    )
                    return repr(interpolated)
            elif value is not None:
                constant_value = value

                def value_for(ts: float) -> str:
                    return constant_value
            else:
                raise InvalidRange("A value is required for a constant bulk correction.")

            correction_ids: list[int] = []
            for row in targets:
                row_value = value_for(float(row["ts"]))
                correction_ids.append(
                    self._apply_one_correction(
                        cur,
                        entity_id=entity_id,
                        sensor_type=sensor_type,
                        stats_metadata=stats_metadata,
                        state_id=row["state_id"],
                        expected_original=None,
                        new_value=row_value,
                        quality=quality,
                        note=note,
                        created_by=created_by,
                    )
                )

        return BulkCorrectionResult(
            entity_id=entity_id,
            correction_ids=correction_ids,
            applied=len(correction_ids),
            skipped=len(rows) - len(targets),
        )
