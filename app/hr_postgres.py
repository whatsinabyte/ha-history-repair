class PostgresAdapter(DatabaseAdapter):
    """Talks to the recorder database over TCP, one connection per operation."""

    def __init__(self, config: DatabaseConfig) -> None:
        self._config = config
        self._lock = threading.Lock()
        # statistics_meta gained mean_type in schema 48 and has_mean is
        # deprecated from HA 2026.11, so the sensor-type expression is built
        # from whichever columns this database actually has.
        self._stats_meta_columns: set[str] | None = None
        self._statistics_columns_cache: dict[str, set[str]] = {}

    # -- connection --------------------------------------------------------

    def _connect(self) -> psycopg.Connection[dict[str, Any]]:
        try:
            conn = psycopg.connect(
                host=self._config.host,
                port=self._config.port,
                user=self._config.user,
                password=self._config.password,
                dbname=self._config.name,
                row_factory=dict_row,
                autocommit=False,
                connect_timeout=10,
            )
        except psycopg.Error as err:
            raise ConnectionFailed(str(err)) from err

        try:
            # PostgreSQL's equivalent of innodb_lock_wait_timeout, in
            # milliseconds. Bounds how long a correction waits for a row the
            # recorder is holding before giving up with LockTimeout, rather
            # than hanging a web request indefinitely.
            conn.execute(f"SET lock_timeout = '{int(self._config.lock_wait_timeout) * 1000}ms'")
            conn.commit()
        except psycopg.Error as err:
            conn.close()
            raise ConnectionFailed(str(err)) from err
        return conn

    @contextmanager
    def _cursor(self) -> Iterator[Any]:
        """A read-only cursor on a short-lived connection."""
        conn = self._connect()
        try:
            with conn.cursor() as cur:
                yield cur
        finally:
            conn.close()

    @contextmanager
    def _transaction(self) -> Iterator[Any]:
        """A write transaction, committed on success and rolled back on error."""
        conn = self._connect()
        try:
            with conn.cursor() as cur:
                try:
                    yield cur
                    conn.commit()
                except Exception:
                    conn.rollback()
                    raise
        except (pg_errors.LockNotAvailable, pg_errors.DeadlockDetected) as err:
            raise LockTimeout(
                "The recorder is currently holding this row. Please try again."
            ) from err
        except pg_errors.QueryCanceled as err:
            # A statement_timeout, or a lock_timeout that surfaced as a
            # cancellation rather than LockNotAvailable. Either way the work
            # did not happen and retrying is the right advice.
            raise LockTimeout(
                "The database cancelled the query before it completed. Please try again."
            ) from err
        finally:
            conn.close()

    @staticmethod
    @contextmanager
    def _savepoint(cur: Any) -> Iterator[None]:
        """Let one statement fail without aborting the whole transaction.

        PostgreSQL marks a transaction unusable after any error: every later
        statement raises InFailedSqlTransaction until it ends. The audit table
        does not exist until onboarding, so several read paths deliberately
        attempt a query against it and carry on when it is missing — a pattern
        that works unchanged on MySQL and SQLite but would poison everything
        afterwards here. Wrapping those attempts in a savepoint makes the
        failure recoverable, which is what keeps those paths working before
        onboarding and, for bulk corrections, keeps one optional lookup from
        taking down an in-progress write transaction.
        """
        cur.execute(f"SAVEPOINT {_AUDIT_PROBE_SAVEPOINT}")
        try:
            yield
        except Exception:
            cur.execute(f"ROLLBACK TO SAVEPOINT {_AUDIT_PROBE_SAVEPOINT}")
            raise
        else:
            cur.execute(f"RELEASE SAVEPOINT {_AUDIT_PROBE_SAVEPOINT}")

    def close(self) -> None:
        # Connections are per-operation; nothing is held open.
        return None

    # -- startup gates -----------------------------------------------------

    def check_health(self) -> HealthReport:
        errors: list[str] = []
        warnings: list[str] = []
        schema_version: int | None = None
        server_version: str | None = None
        can_update = False
        audit_ready = False

        try:
            with self._cursor() as cur:
                cur.execute("SELECT current_setting('server_version') AS v")
                row = cur.fetchone()
                server_version = f"PostgreSQL {row['v']}" if row else None

                schema_version = self._read_schema_version(cur)
                if schema_version is None:
                    errors.append(
                        "Could not read the recorder schema version. Is this the "
                        "Home Assistant database?"
                    )
                elif schema_version < MIN_SCHEMA_VERSION:
                    errors.append(
                        f"Recorder schema {schema_version} is too old. This add-on needs "
                        f"schema {MIN_SCHEMA_VERSION} or newer (Home Assistant 2022.4 and "
                        "later). Please update Home Assistant first."
                    )

                can_update = self._has_update_privilege(cur)
                if not can_update:
                    errors.append(
                        "The database user lacks the UPDATE privilege on the recorder "
                        f"tables in '{self._config.name}'. Grant it with: "
                        f"GRANT UPDATE ON ALL TABLES IN SCHEMA public TO "
                        f"{self._config.user};"
                    )

                cur.execute("SELECT to_regclass('state_corrections') AS t")
                audit_row = cur.fetchone()
                audit_ready = bool(audit_row and audit_row["t"])
        except ConnectionFailed as err:
            return HealthReport(connected=False, errors=[str(err)])

        return HealthReport(
            connected=True,
            schema_version=schema_version,
            server_version=server_version,
            can_update=can_update,
            audit_table_ready=audit_ready,
            errors=errors,
            warnings=warnings,
        )

    @classmethod
    def _read_schema_version(cls, cur: Any) -> int | None:
        try:
            with cls._savepoint(cur):
                cur.execute("SELECT MAX(schema_version) AS v FROM schema_changes")
                row = cur.fetchone()
        except psycopg.Error:
            # Not the recorder database, or the table is not readable. The
            # savepoint above means this leaves the connection usable for the
            # remaining health checks rather than aborting all of them.
            return None
        if row and row["v"] is not None:
            return int(row["v"])
        return None

    @staticmethod
    def _has_update_privilege(cur: Any) -> bool:
        """Can this user UPDATE the one table a correction actually writes?

        Asked directly of PostgreSQL rather than parsed out of a grant listing
        the way the MariaDB adapter has to: has_table_privilege resolves role
        membership and inherited grants itself, so it answers the question
        that actually matters instead of approximating it.
        """
        try:
            cur.execute("SELECT has_table_privilege('states', 'UPDATE') AS ok")
            row = cur.fetchone()
        except psycopg.Error:
            # Cannot introspect; assume the privilege exists and let a real
            # correction fail loudly rather than block the user on a guess.
            return True
        return bool(row and row["ok"])

    def ensure_audit_table(self) -> None:
        with self._transaction() as cur:
            cur.execute(AUDIT_TABLE_DDL)
            for migration in _AUDIT_TABLE_MIGRATIONS:
                cur.execute(migration)
            for index in _AUDIT_TABLE_INDEXES:
                cur.execute(index)

    # -- sensor type -------------------------------------------------------

    def _statistics_meta_columns(self) -> set[str]:
        if self._stats_meta_columns is None:
            with self._cursor() as cur:
                cur.execute(
                    "SELECT column_name AS c FROM information_schema.columns "
                    "WHERE table_schema = current_schema() "
                    "AND table_name = 'statistics_meta'"
                )
                self._stats_meta_columns = {r["c"].lower() for r in cur.fetchall()}
        return self._stats_meta_columns

    def _sensor_type_expressions(self) -> tuple[str, str]:
        """Raw (has_sum, has_mean) SQL expressions, for both SELECT and WHERE use.

        Both evaluate to BOOLEAN, not 0/1 as in the MariaDB adapter: these are
        real boolean columns here, and mixing them with integers in a COALESCE
        or a CASE is a type error PostgreSQL refuses outright.

        Kept separate from _sensor_type_columns's "AS has_sum" aliasing
        because a WHERE clause at the same query level cannot reference a
        SELECT-list alias — filtering by sensor type needs the raw expression
        again, not the name it is given in the SELECT list.
        """
        cols = self._statistics_meta_columns()
        has_sum = "stm.has_sum" if "has_sum" in cols else "FALSE"

        # mean_type is authoritative wherever it exists. Home Assistant stopped
        # populating has_mean once mean_type arrived: on a current install the
        # old column is NULL for every row, so preferring it classifies every
        # measurement sensor as UNKNOWN and refuses to correct any of them.
        # has_mean is still consulted as a fallback, because rows written
        # before the migration keep their value while mean_type is NULL.
        if "mean_type" in cols and "has_mean" in cols:
            has_mean = (
                "CASE WHEN stm.mean_type IS NOT NULL THEN (stm.mean_type > 0) ELSE stm.has_mean END"
            )
        elif "mean_type" in cols:
            # mean_type 0 means no mean; anything above is arithmetic or circular.
            has_mean = "(stm.mean_type > 0)"
        elif "has_mean" in cols:
            has_mean = "stm.has_mean"
        else:
            has_mean = "FALSE"
        return has_sum, has_mean

    def _sensor_type_columns(self) -> str:
        """SELECT-list fragment exposing the sensor-type inputs as has_sum/has_mean."""
        has_sum, has_mean = self._sensor_type_expressions()
        return f"{has_sum} AS has_sum, {has_mean} AS has_mean"

    def _sensor_type_where(self, sensor_type: SensorType) -> str:
        """WHERE fragment restricting to entities classified as exactly this type.

        Mirrors sensor_type_from_flags's own precedence (a sum wins over a
        mean) so filtering agrees with how every other entity_type
        classification in this adapter already works.
        """
        has_sum, has_mean = self._sensor_type_expressions()
        if sensor_type is SensorType.COUNTER:
            return f"COALESCE({has_sum}, FALSE)"
        if sensor_type is SensorType.MEASUREMENT:
            return f"NOT COALESCE({has_sum}, FALSE) AND COALESCE({has_mean}, FALSE)"
        return f"NOT COALESCE({has_sum}, FALSE) AND NOT COALESCE({has_mean}, FALSE)"

    @staticmethod
    def _entity_sort_expr(sort: str, sort_dir: str, *, outer: bool = False) -> str:
        """ORDER BY fragment for list_entities, from an allowlisted key/direction.

        Never built from the raw request values directly: sort and sort_dir
        are looked up against fixed dicts, so an unrecognised value falls back
        to the default rather than ever reaching SQL as text.

        `outer` selects the outer query's own column names, because
        list_entities needs this ordering applied *twice*. A subquery's ORDER
        BY does not survive the joins wrapped around it: SQL only guarantees
        the order a query returns when its outermost level says so, and
        PostgreSQL genuinely exercises that freedom — with the seeded fixture
        the planner picks a Hash Right Join whose output follows its probe
        side (a sequential scan of `states`), handing back rows in physical
        order no matter how the subquery was sorted. The inner ORDER BY is
        still required, since it is what decides *which* page of entities
        LIMIT/OFFSET selects; the outer one is what decides the order they
        are then presented in.
        """
        direction = "DESC" if sort_dir == "desc" else "ASC"
        prefix = "m." if outer else ""
        if sort == "last_updated":
            # NULLS LAST regardless of direction: an entity with no states at
            # all should not jump to the top of a "most recently updated"
            # sort. PostgreSQL says this directly, where MySQL needs a
            # separate (x IS NULL) sort key to express the same thing.
            return f"{prefix}latest_ts {direction} NULLS LAST"
        if sort == "corrections":
            return f"{prefix}correction_count {direction}"
        return f"{'m.' if outer else 'sm.'}entity_id {direction}"

    @staticmethod
    def sensor_type_from_flags(has_sum: Any, has_mean: Any) -> SensorType:
        """Classify a sensor from its statistics_meta flags.

        A sum takes precedence: an energy meter may carry both flags, and its
        cumulative total is what makes it a counter.
        """
        if has_sum:
            return SensorType.COUNTER
        if has_mean:
            return SensorType.MEASUREMENT
        return SensorType.UNKNOWN

    @classmethod
    def _sensor_type(cls, row: dict[str, Any]) -> SensorType:
        return cls.sensor_type_from_flags(row.get("has_sum"), row.get("has_mean"))

    # -- entity browser ----------------------------------------------------

    def _entity_filter_clause(
        self, search: str | None, sensor_type: SensorType | None
    ) -> tuple[str, list[Any]]:
        clauses: list[str] = []
        params: list[Any] = []
        if search:
            # ILIKE, not LIKE: PostgreSQL's LIKE is case-sensitive, while
            # MySQL's default collation folds case. The entity search box is
            # expected to match regardless of how the user typed it, so the
            # case-insensitive operator is what reproduces that behaviour.
            clauses.append(r"sm.entity_id ILIKE %s ESCAPE '\'")
            params.append(f"%{escape_like(search)}%")
        if sensor_type is not None:
            clauses.append(self._sensor_type_where(sensor_type))
        where = f"WHERE {' AND '.join(clauses)}" if clauses else ""
        return where, params

    def count_entities(
        self, search: str | None = None, sensor_type: SensorType | None = None
    ) -> int:
        where, params = self._entity_filter_clause(search, sensor_type)
        # nosec B608 - where is built from _entity_filter_clause, whose only
        # interpolations are the fixed ILIKE fragment and _sensor_type_where's
        # introspected column allowlist; the search term is bound as a
        # parameter.
        sql = f"""
            SELECT COUNT(*) AS n
            FROM states_meta sm
            LEFT JOIN statistics_meta stm ON stm.statistic_id = sm.entity_id
            {where}
        """  # nosec B608
        with self._cursor() as cur:
            cur.execute(sql, params)
            return int(cur.fetchone()["n"])

    def _list_entities_sql(
        self, where: str, order_by: str, correction_expr: str, outer_order_by: str
    ) -> str:
        # nosec B608 - the only interpolations are the fixed WHERE fragment
        # from _entity_filter_clause, _sensor_type_columns()'s introspected
        # column allowlist, _entity_sort_expr's own allowlisted mapping, and
        # correction_expr, which is either the fixed subquery below or the
        # literal fallback list_entities substitutes when state_corrections
        # does not exist yet; the search term is bound as a parameter.
        #
        # shared_attrs is selected raw and parsed in Python (_friendly_name):
        # it is TEXT rather than jsonb, so a SQL-side cast to reach one key
        # would raise on any row that is not valid JSON and take the whole
        # query down with it.
        return f"""
            SELECT
              m.metadata_id,
              m.entity_id,
              s.state                 AS last_value,
              m.latest_ts             AS last_updated_ts,
              m.unit                  AS unit,
              m.has_sum               AS has_sum,
              m.has_mean              AS has_mean,
              m.correction_count      AS correction_count,
              sa.shared_attrs         AS shared_attrs
            FROM (
              SELECT sm.metadata_id, sm.entity_id,
                stm.unit_of_measurement AS unit,
                {self._sensor_type_columns()},
                (SELECT s2.state_id FROM states s2
                  WHERE s2.metadata_id = sm.metadata_id
                  ORDER BY s2.last_updated_ts DESC LIMIT 1) AS last_state_id,
                (SELECT s2.last_updated_ts FROM states s2
                  WHERE s2.metadata_id = sm.metadata_id
                  ORDER BY s2.last_updated_ts DESC LIMIT 1) AS latest_ts,
                {correction_expr} AS correction_count
              FROM states_meta sm
              LEFT JOIN statistics_meta stm ON stm.statistic_id = sm.entity_id
              {where}
              ORDER BY {order_by}
              LIMIT %s OFFSET %s
            ) m
            LEFT JOIN states s            ON s.state_id = m.last_state_id
            LEFT JOIN state_attributes sa ON sa.attributes_id = s.attributes_id
            ORDER BY {outer_order_by}
        """  # nosec B608

    def list_entities(
        self,
        search: str | None = None,
        sensor_type: SensorType | None = None,
        sort: str = "entity_id",
        sort_dir: str = "asc",
        limit: int = 100,
        offset: int = 0,
    ) -> list[Entity]:
        where, params = self._entity_filter_clause(search, sensor_type)
        order_by = self._entity_sort_expr(sort, sort_dir)
        outer_order_by = self._entity_sort_expr(sort, sort_dir, outer=True)
        params.extend([limit, offset])

        # Filtering, sorting, and paging all happen inside the subquery this
        # builds, before any per-entity lookup runs — that is what keeps the
        # cost proportional to the page size rather than to the size of
        # states, which on a busy installation holds tens of millions of
        # rows. Each of latest_ts and correction_count is one correlated,
        # indexed lookup per states_meta row, so its cost scales with entity
        # count, not state count — the same shape statistics_meta already has.
        #
        # No COLLATE clause, unlike the MariaDB adapter: PostgreSQL compares
        # two VARCHARs in the same database collation without complaint, so
        # the collation-mismatch error (MySQL 1267) that forced an explicit
        # COLLATE there has no equivalent here.
        correction_expr = (
            "(SELECT COUNT(*) FROM state_corrections sc "
            "WHERE sc.entity_id = sm.entity_id AND sc.restored_at IS NULL)"
        )
        sql = self._list_entities_sql(where, order_by, correction_expr, outer_order_by)
        with self._cursor() as cur:
            try:
                with self._savepoint(cur):
                    cur.execute(sql, params)
                    rows = cur.fetchall()
            except psycopg.Error as err:
                if not self._is_missing_audit_table(err):
                    raise
                # state_corrections is created during onboarding, so this path
                # has to work without it too — before onboarding, and whenever
                # the adapter is pointed at a database purely to look. No
                # audit table yet means no corrections yet either. The
                # savepoint above is what leaves this connection usable for
                # the retry; without it the transaction would be aborted.
                sql = self._list_entities_sql(where, order_by, "0", outer_order_by)
                cur.execute(sql, params)
                rows = cur.fetchall()

        return [
            self._row_to_entity(r, {r["entity_id"]: r["correction_count"] for r in rows})
            for r in rows
        ]

    def get_entity(self, entity_id: str) -> Entity:
        # nosec B608 - interpolates only _sensor_type_columns(); entity_id is
        # bound as a parameter.
        sql = f"""
            SELECT
              sm.metadata_id,
              sm.entity_id,
              s.state                 AS last_value,
              s.last_updated_ts       AS last_updated_ts,
              stm.unit_of_measurement AS unit,
              {self._sensor_type_columns()},
              sa.shared_attrs         AS shared_attrs
            FROM states_meta sm
            LEFT JOIN states s ON s.state_id = (
              SELECT s2.state_id FROM states s2
               WHERE s2.metadata_id = sm.metadata_id
               ORDER BY s2.last_updated_ts DESC LIMIT 1)
            LEFT JOIN state_attributes sa ON sa.attributes_id = s.attributes_id
            LEFT JOIN statistics_meta stm ON stm.statistic_id = sm.entity_id
            WHERE sm.entity_id = %s
        """  # nosec B608
        with self._cursor() as cur:
            cur.execute(sql, (entity_id,))
            row = cur.fetchone()
        if not row:
            raise NotFound(f"Unknown entity: {entity_id}")
        return self._row_to_entity(row, self._correction_counts([entity_id]))

    @staticmethod
    def _friendly_name(row: dict[str, Any]) -> str | None:
        """Pull friendly_name out of the shared_attrs JSON blob, in Python.

        shared_attrs is TEXT, not jsonb: a SQL-side `::jsonb ->> 'x'` would
        raise on any row whose contents are not valid JSON, failing a query
        over the whole table because of one bad row. Parsing here confines
        that to the single entity it affects.
        """
        raw = row.get("shared_attrs")
        if not raw:
            return None
        try:
            attrs = json.loads(raw)
        except (TypeError, ValueError):
            return None
        name = attrs.get("friendly_name") if isinstance(attrs, dict) else None
        return name if isinstance(name, str) else None

    @classmethod
    def _row_to_entity(cls, row: dict[str, Any], counts: dict[str, int]) -> Entity:
        return Entity(
            metadata_id=row["metadata_id"],
            entity_id=row["entity_id"],
            friendly_name=cls._friendly_name(row),
            sensor_type=cls._sensor_type(row),
            unit=row.get("unit"),
            last_value=row.get("last_value"),
            last_updated_ts=row.get("last_updated_ts"),
            correction_count=counts.get(row["entity_id"], 0),
        )

    @staticmethod
    def _is_missing_audit_table(err: psycopg.Error) -> bool:
        """Is this the audit table simply not existing yet?

        It is created during onboarding, so every read path has to work
        without it: before onboarding, and whenever the adapter is pointed at
        a recorder database purely to look.
        """
        return isinstance(err, pg_errors.UndefinedTable)

    def _correction_counts(self, entity_ids: list[str]) -> dict[str, int]:
        if not entity_ids:
            return {}
        with self._cursor() as cur:
            try:
                with self._savepoint(cur):
                    # ANY(%s) takes the whole list as one parameter, so there
                    # is no run of placeholders to build by hand the way the
                    # MariaDB adapter has to.
                    cur.execute(
                        "SELECT entity_id, COUNT(*) AS n FROM state_corrections "
                        "WHERE restored_at IS NULL AND entity_id = ANY(%s) "
                        "GROUP BY entity_id",
                        (entity_ids,),
                    )
                    rows = cur.fetchall()
            except psycopg.Error as err:
                if self._is_missing_audit_table(err):
                    return {}
                raise
            return {r["entity_id"]: int(r["n"]) for r in rows}

    # -- states ------------------------------------------------------------

    def fetch_states(
        self, entity_id: str, start_ts: float, end_ts: float, limit: int = 20000
    ) -> StateSeries:
        with self._cursor() as cur:
            cur.execute(
                """
                SELECT s.state_id, s.last_updated_ts AS ts, s.state
                  FROM states s
                  JOIN states_meta sm ON sm.metadata_id = s.metadata_id
                 WHERE sm.entity_id = %s
                   AND s.last_updated_ts >= %s
                   AND s.last_updated_ts < %s
                 ORDER BY s.last_updated_ts
                 LIMIT %s
                """,
                # One more than asked for, purely to detect that the window
                # held more rows than fit. The extra row is discarded below.
                (entity_id, start_ts, end_ts, limit + 1),
            )
            rows = cur.fetchall()

            try:
                with self._savepoint(cur):
                    cur.execute(
                        """
                        SELECT id, state_id, orig_state_value
                          FROM state_corrections
                         WHERE entity_id = %s AND restored_at IS NULL
                           AND state_ts >= %s AND state_ts < %s
                        """,
                        (entity_id, start_ts, end_ts),
                    )
                    corrected = {
                        r["state_id"]: (r["id"], r["orig_state_value"])
                        for r in cur.fetchall()
                        if r["state_id"] is not None
                    }
            except psycopg.Error as err:
                if not self._is_missing_audit_table(err):
                    raise
                # No audit table yet, so nothing has been corrected and there
                # is nothing to mark on the graph.
                corrected = {}

        truncated = len(rows) > limit
        points: list[StatePoint] = []
        for r in rows[:limit]:
            mark = corrected.get(r["state_id"])
            points.append(
                StatePoint(
                    state_id=r["state_id"],
                    ts=float(r["ts"]),
                    value=r["state"],
                    numeric_value=to_float(r["state"]),
                    correction_id=mark[0] if mark else None,
                    original_value=mark[1] if mark else None,
                )
            )
        return StateSeries(points=points, truncated=truncated, limit=limit)

    # -- statistics --------------------------------------------------------

    def get_statistics_metadata(self, entity_id: str) -> StatisticsMetadata | None:
        cols = self._statistics_meta_columns()
        # mean_type arrived in schema 48. On anything older the sensor's mean
        # behaviour has to be inferred from has_mean instead.
        mean_type_expr = "stm.mean_type" if "mean_type" in cols else "NULL"
        with self._cursor() as cur:
            cur.execute(
                f"""
                SELECT stm.id, stm.statistic_id, stm.has_sum,
                       stm.unit_of_measurement, {mean_type_expr} AS mean_type,
                       {"stm.has_mean" if "has_mean" in cols else "NULL"} AS has_mean
                  FROM statistics_meta stm
                 WHERE stm.statistic_id = %s
                """,  # nosec B608 - column names come from an introspected allowlist
                (entity_id,),
            )
            row = cur.fetchone()
        if not row:
            return None

        mean_type = row["mean_type"]
        if mean_type is None:
            # Pre-migration row, or a schema without the column: fall back to
            # has_mean, mapping it onto the arithmetic mean type.
            mean_type = 1 if row["has_mean"] else 0

        return StatisticsMetadata(
            id=int(row["id"]),
            statistic_id=row["statistic_id"],
            mean_type=int(mean_type),
            has_sum=bool(row["has_sum"]),
            unit_of_measurement=row["unit_of_measurement"],
        )

    def fetch_readings(self, entity_id: str, start_ts: float, end_ts: float) -> list[Reading]:
        with self._cursor() as cur:
            return self._readings_with(cur, entity_id, start_ts, end_ts)

    @staticmethod
    def _readings_with(cur: Any, entity_id: str, start_ts: float, end_ts: float) -> list[Reading]:
        """Readings for a window, on a caller-supplied cursor.

        Taking the cursor matters: during a correction this has to run inside
        the same transaction as the states UPDATE, so that it sees the
        corrected value rather than the one being replaced.
        """
        # The reading in effect when the window opened. Home Assistant carries
        # this one in, and both the time-weighted mean and the extremes change
        # if it is left out.
        cur.execute(
            """
            SELECT s.state, s.last_updated_ts
              FROM states s
              JOIN states_meta sm ON sm.metadata_id = s.metadata_id
             WHERE sm.entity_id = %s
               AND s.last_updated_ts < %s
               AND s.state NOT IN ('unknown', 'unavailable')
             ORDER BY s.last_updated_ts DESC
             LIMIT 1
            """,
            (entity_id, start_ts),
        )
        rows = list(cur.fetchall())

        cur.execute(
            """
            SELECT s.state, s.last_updated_ts
              FROM states s
              JOIN states_meta sm ON sm.metadata_id = s.metadata_id
             WHERE sm.entity_id = %s
               AND s.last_updated_ts >= %s
               AND s.last_updated_ts < %s
               AND s.state NOT IN ('unknown', 'unavailable')
             ORDER BY s.last_updated_ts
            """,
            (entity_id, start_ts, end_ts),
        )
        rows.extend(cur.fetchall())

        readings: list[Reading] = []
        for row in rows:
            value = to_float(row["state"])
            if value is None:
                # Neither numeric nor one of the sentinels the query filters.
                # The recorder ignores these too.
                continue
            readings.append(Reading(value=value, ts=float(row["last_updated_ts"])))
        return readings

    def fetch_statistics(
        self,
        metadata_id: int,
        start_ts: float,
        end_ts: float,
        short_term: bool = False,
    ) -> list[StatisticsRow]:
        with self._cursor() as cur:
            return self._statistics_with(cur, metadata_id, start_ts, end_ts, short_term)

    def _statistics_with(
        self,
        cur: Any,
        metadata_id: int,
        start_ts: float,
        end_ts: float,
        short_term: bool = False,
    ) -> list[StatisticsRow]:
        table = "statistics_short_term" if short_term else "statistics"
        cols = self._statistics_columns(table)
        # mean_weight arrived in schema 53; selecting it unconditionally would
        # break every older installation.
        mean_weight = "mean_weight" if "mean_weight" in cols else "NULL AS mean_weight"

        # min, max, sum and state are function or keyword names in other
        # contexts but are accepted unquoted as column references here —
        # verified directly against the real schema rather than assumed.
        cur.execute(
            f"""
            SELECT id, metadata_id, start_ts, mean, {mean_weight},
                   min, max, state, sum
              FROM {table}
             WHERE metadata_id = %s AND start_ts >= %s AND start_ts < %s
             ORDER BY start_ts
            """,  # nosec B608 - table and columns come from fixed values above
            (metadata_id, start_ts, end_ts),
        )
        return [
            StatisticsRow(
                id=int(r["id"]),
                metadata_id=int(r["metadata_id"]),
                start_ts=float(r["start_ts"]),
                mean=r["mean"],
                mean_weight=r["mean_weight"],
                min=r["min"],
                max=r["max"],
                state=r["state"],
                sum=r["sum"],
            )
            for r in cur.fetchall()
        ]

    def _statistics_columns(self, table: str) -> set[str]:
        """Columns present on a statistics table, cached per table."""
        if table not in self._statistics_columns_cache:
            with self._cursor() as cur:
                cur.execute(
                    "SELECT column_name AS c FROM information_schema.columns "
                    "WHERE table_schema = current_schema() AND table_name = %s",
                    (table,),
                )
                self._statistics_columns_cache[table] = {r["c"].lower() for r in cur.fetchall()}
        return self._statistics_columns_cache[table]

