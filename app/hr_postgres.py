"""PostgreSQL implementation of DatabaseAdapter.

PostgreSQL is the third recorder backend Home Assistant officially supports,
alongside SQLite (the default) and MariaDB/MySQL. The queries target recorder
schema 28 and above, where states.entity_id has been replaced by a metadata_id
foreign key into states_meta.

Structurally this mirrors hr_mariadb.py — both talk to a server over TCP with
`%s` placeholders and a real transaction per write — so the two read almost
line for line. What differs is dialect, and every difference below was
confirmed against a real PostgreSQL 17 running Home Assistant's own SQLAlchemy
schema rather than assumed from the MySQL original:

* **An error aborts the whole transaction.** This is the big one. In MySQL a
  failed statement is just a failed statement and the next one runs; in
  PostgreSQL every subsequent statement raises InFailedSqlTransaction until
  the transaction ends. Both other adapters lean on try/except around an
  optional `state_corrections` query — the audit table does not exist until
  onboarding — which here would poison everything after it. `_savepoint()`
  below is what makes that pattern work: the optional query runs inside a
  SAVEPOINT that is rolled back on failure, leaving the surrounding
  transaction usable. Skipping it does not fail loudly at the point of the
  mistake; it fails later, somewhere else, which is why it is called out here.

* **has_mean / has_sum are real BOOLEANs**, not MySQL's TINYINT(1) or SQLite's
  INTEGER. `COALESCE(has_sum, 0) = 1` — exactly what hr_mariadb.py writes — is
  a hard type error here ("COALESCE types boolean and integer cannot be
  matched"), so the sensor-type expressions are boolean-native throughout.

* **LIKE is case-sensitive.** MySQL's default collation makes `LIKE` fold
  case, and the entity search box relies on that. PostgreSQL needs ILIKE for
  the same behaviour; plain LIKE would silently return nothing for a search
  typed in the wrong case.

* **No lastrowid.** psycopg has no equivalent, so the audit INSERT carries a
  RETURNING clause instead — which is the better mechanism anyway, being
  explicit about which column it hands back.

* **Row locking and lock timeouts.** `FOR UPDATE OF s` names the table to lock
  so a join does not also lock states_meta. The wait is bounded by the
  session's `lock_timeout` rather than MySQL's innodb_lock_wait_timeout, and
  exceeding it surfaces as LockNotAvailable (55P03), not a MySQL error code.

* **friendly_name is parsed in Python.** state_attributes.shared_attrs is
  TEXT, not jsonb, so casting it in SQL to reach one key would raise on any
  row whose contents are not valid JSON — taking down a query over the whole
  table for one bad row. hr_sqlite.py already parses it in Python for its own
  reasons; this does the same.
"""

